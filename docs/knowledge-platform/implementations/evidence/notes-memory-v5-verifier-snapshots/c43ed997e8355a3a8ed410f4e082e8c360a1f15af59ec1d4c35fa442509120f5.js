#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const { loadBody, compile } = require('./lib/notes-learning-compiler');
const { availableContent } = require('../miniprogram/subpackages/note/services/learning-content');
const root = path.resolve(__dirname, '..');
function build() {
  const args = process.argv.slice(2);
  if (args.some((a) => !['--check-only', '--release', '--review-report'].includes(a))) throw new Error('未知构建参数');
  const source = JSON.parse(fs.readFileSync(path.join(root, 'docs/knowledge-platform/content/notes/learning-v1.json'), 'utf8'));
  if (args.includes('--release') && args.includes('--review-report')) throw new Error('候选审核单与正式构建请分别执行');
  const body = loadBody(root), pack = compile(source, body);
  const candidate = availableContent(body, pack, true), released = availableContent(body, pack, false);
  if (args.includes('--release') && !released.resources.length) throw new Error('没有完成来源及内容审核的正式练习资源');
  const outputPack = args.includes('--release') ? { ...pack,
    targets: released.targets, knowledgeAtoms: released.knowledgeAtoms, comparisonGroups: released.comparisonGroups,
    questions: pack.questions.filter((q) => released.resources.some((r) => r.id === q.id)),
    recipes: pack.recipes.filter((q) => released.resources.some((r) => r.id === q.id)), materials: released.materials,
    sourceReviews: pack.sourceReviews.filter((r) => r.status === 'approved' && r.reviewVerified),
    entryPlans: Object.fromEntries(Object.entries(pack.entryPlans).map(([k, v]) => [k, { resourceIds: v.resourceIds.filter((id) => released.resources.some((r) => r.id === id)) }])) } : pack;
  const output = `// Generated by scripts/build-notes-learning.js. Edit the authored source.\nmodule.exports=${JSON.stringify(outputPack)};\n`;
  const destination = path.join(root, 'miniprogram/subpackages/note/models/learning-pack.js');
  if (args.includes('--check-only')) {
    if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) throw new Error('笔记练习运行包与来源不一致');
  } else { fs.mkdirSync(path.dirname(destination), { recursive: true }); fs.writeFileSync(destination, output); }
  if (args.includes('--review-report')) {
    const report = require('./lib/notes-learning-review').reviewReport(source, pack);
    const reportPath = path.join(root, 'docs/knowledge-platform/implementations/notes-learning-v1-content-review.md');
    if (args.includes('--check-only')) {
      if (!fs.existsSync(reportPath) || fs.readFileSync(reportPath, 'utf8') !== report) throw new Error('审核单与候选来源不一致');
    } else fs.writeFileSync(reportPath, report);
  }
  console.log(JSON.stringify({ passed: true, version: pack.version, questions: pack.questions.length,
    activeQuestions: candidate.resources.filter(r=>r.resourceType==='question').length, historicalQuestionRecords: pack.questions.length-candidate.resources.filter(r=>r.resourceType==='question').length, knowledgeAtoms:pack.knowledgeAtoms?.length||0, comparisonGroups:pack.comparisonGroups?.length||0,
    recipes: pack.recipes.length, developmentResources: candidate.resources.length, approvedResources: released.resources.length, checkOnly: args.includes('--check-only') }));
}
if (require.main === module) { try { build(); } catch (error) { console.error(error.message); process.exitCode = 1; } }
module.exports = { build };
