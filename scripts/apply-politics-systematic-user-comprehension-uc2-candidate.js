const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { compile } = require('./build-politics-systematic-units');
const { renderReading } = require('./refine-politics-systematic-learning');

const root = path.resolve(__dirname, '..');
const SOURCE_PATH = 'docs/knowledge-pilot/sources/politics/systematic-learning-v2-samples.json';
const INVENTORY_PATH = 'docs/knowledge-pilot/sources/politics/systematic-learning-v2-content-inventory.json';
const READING_PATH = 'docs/knowledge-platform/implementations/politics-systematic-understanding-v2-content-samples-20261020.md';
const RUNTIME_PATH = 'miniprogram/models/politics-systematic-units-runtime.js';
const PROPOSAL_PATH = 'docs/knowledge-platform/implementations/evidence/politics-systematic-user-comprehension-uc2-samples-20261023.json';
const EVIDENCE_PATH = 'docs/knowledge-platform/implementations/evidence/politics-systematic-user-comprehension-uc2-runtime-20261023.json';

const absolute = file => path.join(root, file);
const clone = value => JSON.parse(JSON.stringify(value));
const sha256 = value => crypto.createHash('sha256').update(value).digest('hex');
const readJson = file => JSON.parse(fs.readFileSync(absolute(file), 'utf8'));

function sourceIds(value, out = new Set()) {
  if (Array.isArray(value)) value.forEach(item => sourceIds(item, out));
  else if (value && typeof value === 'object') for (const [key, item] of Object.entries(value)) {
    if (key === 'sourceBlockIds') item.forEach(id => out.add(id));
    else sourceIds(item, out);
  }
  return [...out];
}

function rebuildInventory(inventory, samples) {
  const next = clone(inventory);
  const byBlock = new Map();
  for (const lesson of samples.lessons) for (const id of sourceIds(lesson)) {
    if (!byBlock.has(id)) byBlock.set(id, []);
    byBlock.get(id).push(lesson.id);
  }
  for (const unit of next.units) {
    unit.defaultReferencingLessonIds = samples.lessons
      .filter(lesson => lesson.sections.some(part => part.sourceBlockIds.some(id => id.split(':')[1] === unit.unitId)))
      .map(lesson => lesson.id);
    for (const item of unit.sourceBlocks) {
      item.sampleLessonIds = byBlock.get(item.blockId) || [];
      const inDefault = samples.lessons.some(lesson => [...lesson.sections, lesson.boundary, lesson.recap]
        .some(part => part.sourceBlockIds.includes(item.blockId)));
      item.teachingDisposition = inDefault ? 'default-reference' : item.sampleLessonIds.length ? 'optional-reference' : 'source-only';
    }
  }
  return next;
}

function main() {
  const proposal = readJson(PROPOSAL_PATH);
  const sourceBuffer = fs.readFileSync(absolute(SOURCE_PATH));
  const source = JSON.parse(sourceBuffer);
  const inventory = readJson(INVENTORY_PATH);
  delete require.cache[require.resolve('../miniprogram/models/politics-systematic-units-runtime')];
  const currentRuntime = require('../miniprogram/models/politics-systematic-units-runtime');
  const beforeVersion = currentRuntime.curriculumVersion;
  const baselineMatches = sha256(sourceBuffer) === proposal.source.sha256;
  const afterById = new Map(proposal.samples.map(item => [item.lessonId, item.after]));
  const alreadyApplied = proposal.samples.every(item => {
    const current = source.lessons.find(lesson => lesson.id === item.lessonId);
    return JSON.stringify(current) === JSON.stringify(item.after);
  });
  assert.ok(baselineMatches || alreadyApplied, 'current author source is neither the reviewed UC2 baseline nor the reviewed UC2 candidate');

  const next = clone(source);
  next.lessons = next.lessons.map(lesson => afterById.has(lesson.id) ? clone(afterById.get(lesson.id)) : lesson);
  for (const change of proposal.dependentTransitions) next.lessons.find(lesson => lesson.id === change.lessonId).transition = change.after;
  const removed = new Set(proposal.sourceBindingChanges.removedAsUnused);
  next.sourceBindings = next.sourceBindings.filter(item => !removed.has(item.blockId));
  next.progressCompatibleVersions = [...new Set([...(next.progressCompatibleVersions || []), proposal.source.runtimeVersion])];
  const nextInventory = rebuildInventory(inventory, next);
  const runtime = compile(next, nextInventory, 'candidate');
  const runtimeText = '// Generated by scripts/build-politics-systematic-units.js --target=candidate.\nmodule.exports = ' + JSON.stringify(runtime) + ';\n';
  const sourceText = `${JSON.stringify(next, null, 2)}\n`;
  const inventoryText = `${JSON.stringify(nextInventory, null, 2)}\n`;
  const readingText = renderReading(next);

  fs.writeFileSync(absolute(SOURCE_PATH), sourceText);
  fs.writeFileSync(absolute(INVENTORY_PATH), inventoryText);
  fs.writeFileSync(absolute(READING_PATH), readingText);
  fs.writeFileSync(absolute(RUNTIME_PATH), runtimeText);

  const evidence = {
    schemaVersion: 1,
    batchId: 'politics-systematic-user-comprehension-uc2-runtime',
    generatedAt: '2026-10-23',
    status: 'candidate-integrated-for-user-test',
    reviewedProposalPath: PROPOSAL_PATH,
    reviewedProposalSha256: sha256(fs.readFileSync(absolute(PROPOSAL_PATH))),
    sourcePath: SOURCE_PATH,
    sourceSha256: sha256(Buffer.from(sourceText)),
    inventoryPath: INVENTORY_PATH,
    inventorySha256: sha256(Buffer.from(inventoryText)),
    readingPath: READING_PATH,
    readingSha256: sha256(Buffer.from(readingText)),
    runtimePath: RUNTIME_PATH,
    runtimeSha256: sha256(Buffer.from(runtimeText)),
    previousCurriculumVersion: proposal.source.runtimeVersion,
    curriculumVersion: runtime.curriculumVersion,
    candidateOnly: runtime.candidateOnly,
    previousProgressCompatible: runtime.progressCompatibleVersions.includes(proposal.source.runtimeVersion),
    lessonIds: proposal.samples.map(item => item.lessonId),
    lessonTitles: proposal.samples.map(item => item.after.title),
    stableLessonIds: proposal.progressImpact.lessonIdsChanged.length === 0,
    orderChanged: proposal.progressImpact.orderChanged,
    splitOrMerge: proposal.progressImpact.splitOrMerge,
    sourceBindings: next.sourceBindings.length,
    realUserAcceptance: 'pending',
    releaseAuthorized: false,
  };
  fs.writeFileSync(absolute(EVIDENCE_PATH), `${JSON.stringify(evidence, null, 2)}\n`);
  console.log(JSON.stringify({ status: evidence.status, previousCurriculumVersion: evidence.previousCurriculumVersion, curriculumVersion: evidence.curriculumVersion, lessons: evidence.lessonIds.length, progressCompatible: evidence.previousProgressCompatible }));
}

main();
