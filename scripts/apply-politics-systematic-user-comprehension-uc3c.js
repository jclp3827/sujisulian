function main() {
  const source = JSON.parse(fs.readFileSync(absolute(SOURCE), 'utf8'));
  const inventory = JSON.parse(fs.readFileSync(absolute(INVENTORY), 'utf8'));
  delete require.cache[require.resolve('../miniprogram/models/politics-systematic-units-runtime')];
  const previousVersion = require('../miniprogram/models/politics-systematic-units-runtime').curriculumVersion;
  const changedIds = new Set([...Object.keys(titleChanges),...Object.keys(questionChanges),...Object.keys(reflectionChanges)]);
  for (const [id,title] of Object.entries(titleChanges)) source.lessons.find(item=>item.id===id).title=title;
  for (const [id,question] of Object.entries(questionChanges)) source.lessons.find(item=>item.id===id).question=question;
  for (const [id,[prompt,answer]] of Object.entries(reflectionChanges)) {
    const reflection=source.lessons.find(item=>item.id===id).reflection; reflection.prompt=prompt; reflection.answer=answer;
  }
  for (const lesson of source.lessons) {
    if (!lesson.nextLessonId || !lesson.transition.startsWith('下一节：')) continue;
    const next=source.lessons.find(item=>item.id===lesson.nextLessonId); assert.ok(next); lesson.transition=`下一节：${next.title}`;
  }
  source.progressCompatibleVersions=[...new Set([...(source.progressCompatibleVersions||[]),previousVersion])];
  const runtime=compile(source,inventory,'candidate');
  const sourceText=`${JSON.stringify(source,null,2)}\n`;
  const runtimeText=`// Generated by scripts/build-politics-systematic-units.js --target=candidate.\nmodule.exports = ${JSON.stringify(runtime)};\n`;
  fs.writeFileSync(absolute(SOURCE),sourceText);fs.writeFileSync(absolute(RUNTIME),runtimeText);fs.writeFileSync(absolute(READING),renderReading(source));
  const evidence={schemaVersion:1,batchId:'politics-systematic-user-comprehension-uc3c',generatedAt:'2026-10-23',status:'candidate-integrated-for-user-test',
    previousCurriculumVersion:previousVersion,curriculumVersion:runtime.curriculumVersion,progressCompatible:runtime.progressCompatibleVersions.includes(previousVersion),
    stableLessonIds:true,orderChanged:false,changedLessonIds:[...changedIds],sourcePath:SOURCE,sourceSha256:sha256(Buffer.from(sourceText)),runtimePath:RUNTIME,
    runtimeSha256:sha256(Buffer.from(runtimeText)),realUserAcceptance:'pending',releaseAuthorized:false};
  fs.writeFileSync(absolute(EVIDENCE),`${JSON.stringify(evidence,null,2)}\n`);
  console.log(JSON.stringify({status:evidence.status,previousCurriculumVersion:previousVersion,curriculumVersion:runtime.curriculumVersion,changedLessons:changedIds.size,progressCompatible:evidence.progressCompatible}));
}

main();
