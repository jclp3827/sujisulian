#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');

const root = path.resolve(__dirname, '..');
const fixtureRoot = path.join(__dirname, 'fixtures/common-sense-runtime-compatibility');
const modelRoot = path.join(root, 'miniprogram/subpackages/common-sense/models');
const entries = [
  ['guide-learning-compatibility', 'packed-guide-learning-compatibility'],
  ['learning-identity-compatibility', 'packed-learning-identity-compatibility'],
];

function loadFixture(name) {
  const filename = path.join(fixtureRoot, `${name}.js`);
  delete require.cache[require.resolve(filename)];
  return require(filename);
}

function renderPacked(value) {
  const data = zlib.deflateSync(Buffer.from(JSON.stringify(value)), { level: 9 }).toString('base64');
  return `module.exports={"codec":"deflate-base64-v1","data":${JSON.stringify(data)}};\n`;
}

function outputs() {
  return entries.flatMap(([sourceName, packedName]) => {
    const value = loadFixture(sourceName);
    return [
      [path.join(modelRoot, `${packedName}.js`), renderPacked(value)],
      [path.join(modelRoot, `${sourceName}.js`),
        `// Generated by scripts/build-common-sense-runtime-compatibility.js.\nmodule.exports = require("./packed-codec")(require("./${packedName}"));\n`],
    ];
  });
}

function build({ check = false } = {}) {
  const rendered = outputs();
  for (const [filename, value] of rendered) {
    if (check) {
      if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== value) {
        throw new Error(`Generated compatibility file is stale: ${path.relative(root, filename)}`);
      }
    } else {
      fs.writeFileSync(filename, value);
    }
  }
  return rendered.map(([filename, value]) => ({ path: path.relative(root, filename), bytes: Buffer.byteLength(value) }));
}

if (require.main === module) {
  const result = build({ check: process.argv.includes('--check') });
  console.log(JSON.stringify({ passed: true, check: process.argv.includes('--check'), files: result }));
}

module.exports = { build, renderPacked };
