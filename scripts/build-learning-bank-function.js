// Compile only content already admitted by the public learning rules.
// Run before deploying learningBank; source packs are never copied into the mini-program package.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.resolve(__dirname, '..');
const output = path.join(root, 'cloudfunctions', 'learningBank', 'data');
const mini = path.join(root, 'miniprogram');
const fromMini = (relative) => require(path.join(mini, relative));
const stableHash = (value) => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');

function compile() {
  const noteBody = fromMini('subpackages/note/models/note-catalog');
  const notePack = fromMini('subpackages/note/models/learning-pack');
  const noteContent = fromMini('subpackages/note/services/learning-content').availableContent(
    noteBody, notePack, false, { publicReviewed: true });
  if (noteContent.materials.length) throw new Error('Note materials need group-aware cloud batching before deployment');
  const sourceValid = fromMini('subpackages/note/services/learning-content').sourceValid;
  const exposureMap = {};
  notePack.questions.filter((item) => item.origin).forEach((item) => {
    item.refs.filter((ref) => sourceValid(noteBody, ref)).forEach((ref) => {
      const key = JSON.stringify([ref.subjectId, ref.pointId, item.originalExampleFingerprint]);
      const groups = exposureMap[key] ||= [];
      if (!groups.includes(item.exposureGroupId)) groups.push(item.exposureGroupId);
    });
  });
  fs.writeFileSync(path.join(mini, 'subpackages', 'note', 'models', 'example-exposure-map.js'),
    `// Generated by scripts/build-learning-bank-function.js.\nmodule.exports=${JSON.stringify(exposureMap)};\n`);
  const memoryPack = fromMini('subpackages/note/models/memory-pack');
  const memoryCards = fromMini('subpackages/note/services/memory-content').availableCards(
    noteBody, memoryPack, false, { publicReviewed: true });
  const commonBody = fromMini('subpackages/common-sense/models/note-common-sense');
  const commonPack = fromMini('subpackages/common-sense/models/learning-pack');
  const commonContent = fromMini('subpackages/common-sense/services/learning-content').availableContent(
    commonBody, commonPack, false, { publicReviewed: true });
  const commonFingerprint = fromMini('subpackages/common-sense/services/learning-content').fingerprint;
  const questionSpecs = new Map(commonContent.questionSpecifications.map((item) => [item.questionId, item]));
  const questionBodies = commonContent.questions.map((item) => ({ ...item,
    ...(questionSpecs.has(item.id) ? { specification: questionSpecs.get(item.id) } : {}) }));
  const commonBootstrap = { version: commonContent.version, scopeOrder: commonContent.scopeOrder,
    scopes: commonBody.directory.map((item) => ({ id: item.id, title: item.title.replace('常识', '') })),
    entryPlans: commonContent.entryPlans,
    groups: commonContent.groups, examTopics: commonContent.examTopics,
    comparisons: commonContent.comparisons, conceptFrames: commonContent.conceptFrames,
    mnemonicConceptBindings: commonContent.mnemonicConceptBindings,
    questions: commonContent.questions.map((item) => ({ id: item.id, scope: item.scope, group: item.group,
      answer: item.answer, options: Array(item.options.length).fill(''), runtimeSignature: commonFingerprint(item), stub: true })),
    mnemonics: commonContent.mnemonics.map((item) => ({ id: item.id, scope: item.scope,
      revision: item.revision, questionIds: item.questionIds, runtimeSignature: commonFingerprint(item), stub: true,
      phrases: item.phrases.map(({ id, conditionRefs }) => ({ id,
        conditionRefs: (conditionRefs || []).map(({ id: refId }) => ({ id: refId })) })) })) };
  const commonMigrations = commonContent.sessionMigrations.map((item) => ({
    fromVersion: item.fromVersion, toVersion: item.toVersion,
    changedQuestionIds: item.changedQuestionIds, changedMnemonicIds: item.changedMnemonicIds,
    changedComparisonIds: item.changedComparisonIds, changedExamTopicIds: item.changedExamTopicIds,
  }));
  const expansion = fromMini('subpackages/common-sense/models/guide-expansion-candidate');
  const prepared = fromMini('subpackages/common-sense/services/guide-preview-content').prepareExpansionContent(expansion);
  const guideContent = fromMini('subpackages/common-sense/services/guide-content').createGoldenGuideContent(commonBody, prepared);
  const guideBootstrap = { version: guideContent.version, scopeOrder: guideContent.scopeOrder,
    scopes: commonBody.directory.map((item) => ({ id: item.id, title: item.title.replace('常识', '') })),
    stats: guideContent.stats,
    groups: guideContent.groups.map(({ id, scope, title, takeaway, cardIds, signature }) =>
      ({ id, scope, title, takeaway, cardIds, signature })),
    cardSignatures: guideContent.cards.map(({ signature }) => signature) };
  if (guideBootstrap.groups.flatMap((group) => group.cardIds).some((id, index) => id !== guideContent.cards[index]?.id))
    throw new Error('Guide card order is not the flattened group order');
  const commonEntry = fromMini('subpackages/common-sense/services/learning-entry');
  const commonIds = Object.fromEntries(['daily', 'qa', 'confusion', 'exam', 'mnemonic'].map((mode) => [
    mode, [...new Set(['selected', 'review'].flatMap((variant) =>
      commonEntry.entryQuestions(commonContent, mode, 'all', variant).map((item) => item.id)))],
  ]));

  const banks = {
    'note-practice': { version: noteContent.version, items: noteContent.resources,
      modes: Object.fromEntries(['basic', 'method', 'application'].map((mode) => [mode, noteContent.entryPlans[mode].resourceIds])) },
    'note-memory': { version: memoryPack.version, items: memoryCards,
      modes: { basic: memoryCards.filter((item) => item.kind === 'basic').map((item) => item.id),
        method: memoryCards.filter((item) => item.kind === 'method').map((item) => item.id),
        exam: memoryCards.map((item) => item.id) } },
    'common-question': { version: commonContent.version, items: questionBodies, modes: commonIds },
    'common-mnemonic': { version: commonContent.version, items: commonContent.mnemonics,
      modes: { mnemonic: commonContent.mnemonics.map((item) => item.id) } },
    'common-guide': { version: guideContent.version, items: guideContent.cards,
      modes: { guide: guideContent.cards.map((item) => item.id) } },
  };

  fs.rmSync(output, { recursive: true, force: true });
  fs.mkdirSync(output, { recursive: true });
  const manifest = { schema: 1, banks: {} };
  for (const [bankName, bank] of Object.entries(banks)) {
    const name = bankName.replace(/[^a-z-]/g, '');
    const dir = path.join(output, name);
    fs.mkdirSync(dir, { recursive: true });
    const ids = new Set();
    const index = [];
    bank.items.forEach((item, position) => {
      if (!item?.id || ids.has(item.id)) throw new Error(`${bankName}: duplicate or missing item ID`);
      ids.add(item.id);
      const file = String(Math.floor(position / 5)).padStart(4, '0');
      index.push({ id: item.id, file, subjectId: item.subjectId || '', categoryId: item.categoryId || '',
        ...(bankName === 'note-practice' ? { familyId: item.familyId || item.id } : {}),
        scope: item.scope || '', kind: item.kind || '', groupId: item.groupId || item.group || '',
        sources: (item.refs || []).map(({ subjectId, pointId, tabId }) => ({ subjectId, pointId, tabId })),
        title: item.title || item.prompt?.slice(0, 48) || '',
        version: item.semanticVersion || item.revision || item.signature || stableHash(item).slice(0, 12),
        bytes: Buffer.byteLength(JSON.stringify(item)) });
    });
    for (let first = 0; first < bank.items.length; first += 5) {
      const file = String(Math.floor(first / 5)).padStart(4, '0');
      fs.writeFileSync(path.join(dir, `${file}.json`), JSON.stringify(bank.items.slice(first, first + 5)));
    }
    for (const [mode, modeIds] of Object.entries(bank.modes)) {
      if (modeIds.some((id) => !ids.has(id))) throw new Error(`${bankName}/${mode}: public plan refers to unadmitted item`);
    }
    manifest.banks[bankName] = { version: bank.version, count: bank.items.length, hash: stableHash(bank.items),
      index, modes: bank.modes };
  }
  fs.writeFileSync(path.join(output, 'manifest.json'), JSON.stringify(manifest));
  fs.writeFileSync(path.join(output, 'common-guide', 'bootstrap.json'), JSON.stringify(guideBootstrap));
  fs.writeFileSync(path.join(output, 'common-question', 'bootstrap.json'), JSON.stringify(commonBootstrap));
  fs.writeFileSync(path.join(output, 'common-question', 'migrations.json'), JSON.stringify(commonMigrations));
  return manifest;
}

if (require.main === module) {
  const manifest = compile();
  console.log(JSON.stringify(Object.fromEntries(Object.entries(manifest.banks).map(([name, bank]) => [name,
    { count: bank.count, version: bank.version, hash: bank.hash.slice(0, 12) }])), null, 2));
}
module.exports = { compile };
