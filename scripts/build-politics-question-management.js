#!/usr/bin/env node
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { readInputs, build: buildCatalogue } = require('./build-politics-question-catalogue');
const { snapshot, runtimeTargets } = require('./lib/politics-question-management');
const root = path.resolve(__dirname, '..');
const baselinePath = path.join(root, 'docs/knowledge-platform/implementations/evidence/politics-question-management-u2-20261022.json');
const projectionPath = path.join(root, 'miniprogram/subpackages/politics/practice/remedy-targets.js');
function build() {
  const inputs = readInputs(); buildCatalogue(inputs); // Existing source/goal/projection gates must pass before baseline generation.
  const management = snapshot(inputs);
  return { management, projection: runtimeTargets(management, inputs) };
}
function serializeProjection(projection) { return '// Generated by scripts/build-politics-question-management.js. IDs and locations only.\nmodule.exports = ' + JSON.stringify(projection, null, 2) + ';\n'; }
function main() {
  assert.ok(process.argv.slice(2).every(arg => arg === '--check'), 'unknown management build argument');
  const { management, projection } = build();
  const outputs = [[baselinePath, JSON.stringify(management, null, 2) + '\n'], [projectionPath, serializeProjection(projection)]];
  for (const [file, text] of outputs) {
    if (process.argv.includes('--check')) assert.equal(fs.readFileSync(file, 'utf8'), text, `stale management artifact: ${file}`);
    else fs.writeFileSync(file, text);
  }
  console.log(JSON.stringify({ status: 'passed', version: management.snapshotVersion, items: management.items.length, surfaces: management.surfaces.length, remedies: management.remedies.length, projectionBytes: Buffer.byteLength(serializeProjection(projection)) }));
}
if (require.main === module) main();
module.exports = { build, baselinePath, projectionPath, serializeProjection };
