const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { validate } = require('./validate-politics-systematic-content');
const { knowledgePackage } = require('../miniprogram/services/knowledge-platform/politics-runtime');
const root = path.resolve(__dirname, '..');

function compile(samples, inventory, target = 'candidate') {
  if (target !== 'candidate') throw new Error('Draft systematic units are candidate-only; release is not allowed');
  validate(samples, inventory);
  const version = 'units-' + crypto.createHash('sha256').update(JSON.stringify(samples)).digest('hex').slice(0, 12);
  return {
    id: samples.id, curriculumVersion: version, knowledgePackageVersion: knowledgePackage.packageVersion,
    candidateOnly: true, reviewState: 'draft', groups: samples.groups,
    lessons: samples.lessons.map(lesson => ({ ...lesson,
      parts: [...lesson.sections.map((part, i) => ({ ...part, kind: 'explanation', id: `${lesson.id}-body-${i + 1}` })),
        { ...lesson.boundary, kind: 'boundary', id: `${lesson.id}-boundary` },
        { ...lesson.recap, kind: 'recap', id: `${lesson.id}-recap` }],
      sections: undefined, boundary: undefined, recap: undefined,
    })),
  };
}

if (require.main === module) {
  const samples = require('../docs/knowledge-pilot/sources/politics/systematic-learning-v2-samples.json');
  const inventory = require('../docs/knowledge-pilot/sources/politics/systematic-learning-v2-content-inventory.json');
  const target = process.argv.find(arg => arg.startsWith('--target='))?.slice(9) || 'candidate';
  const result = compile(samples, inventory, target);
  const file = path.join(root, 'miniprogram/models/politics-systematic-units-runtime.js');
  const output = '// Generated by scripts/build-politics-systematic-units.js --target=candidate.\nmodule.exports = ' + JSON.stringify(result) + ';\n';
  if (process.argv.includes('--check-only')) {
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== output) throw new Error('Systematic unit runtime is stale');
  } else fs.writeFileSync(file, output);
  console.log(JSON.stringify({status:'passed', target, curriculumVersion: result.curriculumVersion, lessons:result.lessons.length}));
}
module.exports = { compile };
