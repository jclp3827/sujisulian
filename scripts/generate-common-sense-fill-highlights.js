const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const auditDir = path.join(root, 'docs/common-sense-source-audit');
const outputPath = path.join(root, 'miniprogram/models/note-common-sense/note-common-sense-fill-highlights.js');

const splitAnswers = (answer) => String(answer || '')
  .split(/[；;、，,\/]+/)
  .map((item) => item.trim())
  .filter((item) => item && item !== '—');

const mapping = {};
fs.readdirSync(auditDir).filter((name) => name.endsWith('.json')).sort().forEach((name) => {
  const audit = JSON.parse(fs.readFileSync(path.join(auditDir, name), 'utf8'));
  const answers = (audit.fillCompletions || []).flatMap((item) => splitAnswers(item.answer));
  if (answers.length) mapping[audit.pointId] = Array.from(new Set(answers));
});

const source = `// Generated by scripts/generate-common-sense-fill-highlights.js.\n` +
`const FILL_HIGHLIGHTS = ${JSON.stringify(mapping, null, 2)};\n\n` +
`function stringify(value) {\n  if (typeof value === 'string') return value;\n  if (Array.isArray(value)) return value.map(stringify).join(' ');\n  if (value && typeof value === 'object') return Object.values(value).map(stringify).join(' ');\n  return '';\n}\n\n` +
`module.exports = function applyFillHighlights(points) {\n  (points || []).forEach((point) => {\n    const answers = FILL_HIGHLIGHTS[point.id] || [];\n    if (!answers.length) return;\n    point.fillHighlights = answers;\n    point.tabs = (point.tabs || []).map((tab) => ({\n      ...tab,\n      blocks: (tab.blocks || []).map((block) => {\n        const text = stringify(block);\n        const matched = answers.filter((answer) => text.includes(answer));\n        return { ...block, highlights: Array.from(new Set([...(block.highlights || []), ...matched])) };\n      }),\n    }));\n  });\n};\n\nmodule.exports.FILL_HIGHLIGHTS = FILL_HIGHLIGHTS;\n`;

fs.writeFileSync(outputPath, source);
