const assert=require('assert/strict');
const body=require('../miniprogram/subpackages/common-sense/models/note-common-sense');
const original=require('./fixtures/common-sense-energy-before-correction.json');
const oldSafety=require('./fixtures/common-sense-safety-before-correction.json');
const {createGuideContent}=require('../miniprogram/subpackages/common-sense/services/guide-content');
const {createGuideSession}=require('../miniprogram/subpackages/common-sense/services/guide-session');
const clone=x=>JSON.parse(JSON.stringify(x));
const previous=clone(body);previous.points[previous.points.findIndex(p=>p.id===original.id)]=original;
const before=createGuideContent(previous),after=createGuideContent(body);
assert.deepEqual(after.cards.map(c=>c.id),before.cards.map(c=>c.id));
const changed=before.cards.filter(c=>c.signature!==after.cardById[c.id].signature);
assert.deepEqual(changed.map(c=>c.pointId),['current-main-energy','current-main-energy']);
const p=body.points.find(p=>p.id===original.id);
assert.deepEqual(p.tabs.map(t=>t.id),original.tabs.map(t=>t.id));
assert.deepEqual(p.readingMeta.focus.map(x=>x.sourceUnitIds),original.readingMeta.focus.map(x=>x.sourceUnitIds));
assert.ok(!p.readingMeta.takeaway.includes('聚变尚不受控'));
assert.ok(p.readingMeta.review.join('').includes('受控聚变研究'));
const values={},storage={getStorageSync:k=>clone(values[k]||null),setStorageSync:(k,v)=>values[k]=clone(v)};
const first=createGuideSession(before,storage),s=first.start({scope:'all',groupId:original.id,count:5}).session;
first.assess(s,'remembered');
const next=createGuideSession(after,storage);assert.equal(next.resume(s.key),null);assert.equal(next.record(changed[0].id),null);
const combinedPrevious=clone(previous);
for(const p of oldSafety.points)combinedPrevious.points[combinedPrevious.points.findIndex(x=>x.id===p.id)]=p;
const combined=createGuideContent(combinedPrevious);
assert.deepEqual(combined.cards.map(c=>c.id),after.cards.map(c=>c.id));
const combinedChanges=combined.cards.filter(c=>c.signature!==after.cardById[c.id].signature);
assert.equal(combinedChanges.length,12);
assert.ok(combinedChanges.every(c=>['life-safety','safety-common-sense','current-main-energy'].includes(c.pointId)));
console.log(JSON.stringify({ok:true,stableCardIds:653,changedCardSignatures:2,unchangedCardSignatures:651,changedSessionInvalidated:true}));
