const assert=require('assert/strict');
const body=require('../miniprogram/subpackages/common-sense/models/note-common-sense');
const batch=require('../docs/knowledge-platform/content/common-sense-guide-expansion-batch-16');
const {createGoldenGuideContent}=require('../miniprogram/subpackages/common-sense/services/guide-content');
const content=createGoldenGuideContent(body,batch);
assert.deepEqual(content.groups.map(g=>g.id),['life-safety','safety-common-sense']);
assert.equal(content.stats.cards,29);assert.equal(content.stats.holds,0);
assert.deepEqual(content.stats.productionModes,{reuse:6,'light-edit':18,synthesized:5});
assert.equal(content.stats.scopes['science-technology'],29);
const previous=Array.from({length:15},(_,i)=>require(`../docs/knowledge-platform/content/common-sense-guide-expansion-batch-${i+1}`));
const existing=new Set(previous.flatMap(b=>b.groups).map(g=>g.pointId));
assert.ok(batch.groups.every(g=>!existing.has(g.pointId)));
assert.equal(new Set(content.cards.map(c=>c.id)).size,29);
assert.ok(content.cards.every(c=>c.mapping==='source-overlap'));
assert.match(content.cardById['life-safety::bc-dry-powder'].content,/不能直接用于一般固体/);
assert.match(content.cardById['safety-common-sense::coma-not-cpr-indication'].content,/无反应且无正常呼吸/);
const invalid=JSON.parse(JSON.stringify(batch));invalid.groups[0].cards[1].id=invalid.groups[0].cards[0].id;
assert.throws(()=>createGoldenGuideContent(body,invalid),/知识卡标识重复/);
console.log(JSON.stringify({ok:true,batchId:batch.id,groups:2,cards:29,holds:0,exclusions:0},null,2));
