#!/usr/bin/env node
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');
const { validateUserComprehensionLineage } = require('./lib/politics-systematic-user-comprehension-lineage');
const root = path.resolve(__dirname, '..');
const batch = 'politics-systematic-user-comprehension-uc7b-p2';
const read = file => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
const digest = file => crypto.createHash('sha256').update(fs.readFileSync(path.join(root, file))).digest('hex');
const evidence = read('docs/knowledge-platform/implementations/evidence/' + batch + '-20261023.json');
const source = read(evidence.sourcePath);
const runtime = require('../miniprogram/models/politics-systematic-units-runtime');
const service = require('../miniprogram/services/knowledge-platform/systematic-units');
const ai = read(evidence.aiReviewPath), probe = read(evidence.runtimeProbePath);
const { latest } = validateUserComprehensionLineage(root, batch);
const ids = ['SYS-05', 'LEADERSHIP-02'];
assert.equal(latest.batchId, batch);
assert.equal(evidence.status, 'candidate-integrated-and-runtime-verified');
assert.equal(evidence.curriculumVersion, runtime.curriculumVersion);
assert.equal(evidence.previousCurriculumVersion, 'units-a73e58ffcf88');
assert.equal(evidence.stableLessonIds, true);
assert.equal(evidence.orderChanged, false);
assert.equal(evidence.progressCompatible, true);
assert.deepEqual(evidence.changedLessonIds, ids);
assert.deepEqual(evidence.metadataChangedLessonIds, ['LEADERSHIP-01']);
assert.equal(evidence.unaffectedLessonCount, 69);
const unchanged = source.lessons.filter(l => !ids.includes(l.id) && !evidence.metadataChangedLessonIds.includes(l.id));
assert.equal(crypto.createHash('sha256').update(JSON.stringify(unchanged)).digest('hex'), evidence.unaffectedLessonsSha256);
assert.ok(runtime.progressCompatibleVersions.includes(evidence.previousCurriculumVersion));
assert.equal(evidence.realUserAcceptance, 'pending');
assert.equal(evidence.releaseAuthorized, false);
for (const name of ['source', 'inventory', 'runtime', 'projection', 'aiReview', 'runtimeProbe']) {
  assert.equal(digest(evidence[name + 'Path']), evidence[name + 'Sha256'], name + ' hash drift');
}
assert.equal(ai.curriculumVersion, runtime.curriculumVersion);
assert.equal(ai.sourceSha256, evidence.sourceSha256);
assert.equal(ai.projectionSha256, evidence.projectionSha256);
assert.deepEqual(ai.lessonIds, ids);
for (const name of ['ai-first-user','ai-subject-expert','ai-assessment-expert']) {
  const role = ai.roles[name];
  assert.equal(role.status, 'pass'); assert.equal(role.riskCount, 0); assert.equal(role.holdCount, 0);
  assert.deepEqual(Object.keys(role.lessonAssertions).sort(), ids.slice().sort());
}
assert.equal(probe.status, 'passed');
assert.equal(probe.curriculumVersion, runtime.curriculumVersion);
assert.deepEqual(probe.lessonIds, ids);
assert.equal(probe.compileSuccess, true);
assert.equal(probe.automatorVerified, true);
assert.equal(probe.headerDomCheck, 'passed');
for (const id of ids) {
  const l = source.lessons.find(l => l.id === id);
  const compiled = runtime.lessons.find(l => l.id === id);
  const actual = probe.screens.find(s => s.lessonId === id);
  assert.deepEqual(evidence.after[id], l);
  assert.equal(l.boundary, undefined);
  assert.equal(compiled.parts.filter(p => p.kind === 'boundary').length, 0);
  assert.equal(compiled.parts.at(-1).kind, 'recap');
  assert.equal(compiled.parts.at(-1).emphasized, true);
  assert.equal(service.displayTitleForLessonId(id), l.title);
  assert.equal(actual.screen, 'lesson');
  assert.equal(actual.title, l.title);
  assert.equal(actual.question, l.question);
  assert.equal(actual.outcomeSummary, l.objectives.map(service.formatOutcomeObjective).join('；'));
  assert.deepEqual(actual.partLabels, compiled.parts.map(p => p.label));
  assert.deepEqual(actual.partTexts, compiled.parts.map(p => p.text));
  assert.deepEqual(actual.partKinds, compiled.parts.map(p => p.kind));
  assert.deepEqual(actual.partEmphasis, compiled.parts.map(p => Boolean(p.emphasized)));
  assert.deepEqual(actual.reflection, l.reflection);
  assert.ok(Object.values(actual.dom).every(Boolean));
  assert.doesNotMatch(JSON.stringify(l), /六项方法|三项方法|几个定位|先明确面向谁|连同上一小节|放回科学体系/);
  assert.equal(l.reflection.prompt, l.question);
}
const sys = source.lessons.find(l => l.id === 'SYS-05');
assert.equal(sys.title, '六个必须坚持·四至六');
assert.deepEqual(sys.sections.map(p => p.label), ['问题导向（第4项）','系统观念（第5项）','胸怀天下（第6项）']);
assert.ok(sys.sections[0].text.includes('重要实践要求'));
assert.ok(sys.sections[1].text.includes('基本思想和工作方法'));
assert.ok(sys.sections[2].text.includes('中国共产党人的境界格局'));
assert.deepEqual(sys.recap.sourceBlockIds, ['block:politics-toc-v2-u003:b019']);
const leadership = source.lessons.find(l => l.id === 'LEADERSHIP-02');
assert.equal(leadership.title, '人民立场、党的宗旨与群众路线');
assert.deepEqual(leadership.sections[0].sourceBlockIds, ['block:politics-toc-v2-u006:b004']);
assert.deepEqual(leadership.sections[1].sourceBlockIds, ['block:politics-toc-v2-u006:b009','block:politics-toc-v2-u006:b008']);
assert.match(leadership.sections[1].text, /全心全意为人民服务是中国共产党的宗旨；增进民生福祉是发展的根本目的/);
assert.match(leadership.sections[2].text, /一切为了群众、一切依靠群众，从群众中来、到群众中去/);
assert.match(leadership.reflection.answer, /一切为了群众、一切依靠群众，从群众中来、到群众中去/);
assert.equal(source.lessons.find(l => l.id === 'LEADERSHIP-01').transition, '下一节：' + leadership.title);
for (const field of ['existingProgressBeforeProbe','temporaryNavigationStorageFree','storageRecordByteEquivalent']) assert.equal(probe.progressProtection[field], true);
assert.equal(probe.progressProtection.testedCurriculumVersion, runtime.curriculumVersion);
assert.equal(probe.progressProtection.completionStateChangedByProbe, false);
console.log(JSON.stringify({status:'passed',batch,curriculumVersion:runtime.curriculumVersion,changedLessonIds:ids,aiReview:'passed',runtimePageCheck:'passed',realUserAcceptance:'pending'}));
